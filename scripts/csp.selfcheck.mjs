#!/usr/bin/env node
/**
 * Pins the Content-Security-Policy against the BUILT index.html (#csp).
 *
 * This policy has now shipped broken twice, and both times it failed the same
 * way: silently, and looking like something else.
 *
 *   • The Cloud Functions origin was missing from connect-src until three
 *     hours before the first concert that needed it. The function answered
 *     correctly and the browser refused to send the request, which the page
 *     could only report as "That did not reach the Hub."
 *   • media-src was missing entirely (Sept 2026). Storage was already listed
 *     for connect-src, so UPLOADING a playing exam worked and PLAYING one
 *     back did not — the browser refused the media against default-src and
 *     the <video> just sat there with no error. The director's report was
 *     "it won't play, it won't load, nothing", and the first two theories
 *     (preload, then a stale cache) were both wrong.
 *
 * A CSP omission looks exactly like bad wifi from the inside. Nothing throws,
 * no test fails, the feature is simply dead in the browser. So the directives
 * the app cannot work without are asserted here instead of being noticed by a
 * user weeks later.
 *
 * Runs AFTER the build, against dist/index.html — the policy is generated by
 * the vite plugin, so the built file is the only place the real answer exists.
 */
import { readFileSync } from 'node:fs';

const INDEX = new URL('../dist/index.html', import.meta.url);

function fail(msg) {
  console.error(`csp self-check FAILED: ${msg}`);
  process.exit(1);
}

let html;
try {
  html = readFileSync(INDEX, 'utf8');
} catch {
  fail('dist/index.html not found — run this after `npm run build`');
}

const m = html.match(/http-equiv="Content-Security-Policy"\s+content="([^"]+)"/);
if (!m) fail('no CSP meta tag in the built index.html');
const policy = m[1];

const directives = Object.fromEntries(
  policy.split(';').map(d => d.trim()).filter(Boolean).map(d => {
    const [name, ...values] = d.split(/\s+/);
    return [name, values];
  }),
);

function requires(directive, value, why) {
  const values = directives[directive];
  if (!values) {
    fail(`no "${directive}" directive at all. It does NOT fall back to connect-src — `
      + `it falls back to default-src 'self', which blocks everything off-origin. ${why}`);
  }
  if (!values.includes(value)) {
    fail(`"${directive}" is missing ${value}. ${why}\n  got: ${directive} ${values.join(' ')}`);
  }
}

const STORAGE = 'https://firebasestorage.googleapis.com';

// The app's own bucket, as three different sinks. Each needs naming
// separately; allowing one does not allow the others.
requires('media-src', STORAGE,
  'Playing-exam videos stream from Storage into a <video> on the grade sheet and the student page.');
requires('media-src', 'blob:',
  'The in-app recorder previews a take from a blob: URL before the student sends it.');
requires('img-src', STORAGE,
  'Announcement pictures, sign-up reference images and attachment thumbnails are <img> from Storage.');
requires('img-src', 'blob:',
  'A file someone just picked is previewed from a blob: URL before upload.');
requires('connect-src', STORAGE, 'Uploads and downloads.');
requires('connect-src', 'https://firestore.googleapis.com', 'All live data.');

// Guards that must not erode.
if (!directives["object-src"]?.includes("'none'")) fail("object-src must stay 'none'");
if (!directives["base-uri"]?.includes("'self'")) fail("base-uri must stay 'self'");
if (directives['script-src']?.includes("'unsafe-inline'")) {
  fail("script-src must NOT allow 'unsafe-inline' — the inline boot scripts are allowed by sha256 hash");
}
if (!directives['script-src']?.some(v => v.startsWith("'sha256-"))) {
  fail('script-src must carry the sha256 hashes of the inline boot scripts');
}

console.log('csp self-check OK —', Object.keys(directives).length, 'directives');
