#!/usr/bin/env node
// Members-only rules for AISO (#members-gate). The school deploys
// firestore.rules / storage.rules untouched; firebase.aiso.json deploys the
// two files this writes, which are the same rules with every world-readable
// line narrowed to an honoured sign-in. Regenerate after any rules change:
//   node scripts/gate-rules.mjs          (write)
//   node scripts/gate-rules.mjs --check  (exit 1 if the committed copies drifted)
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const HEAD = '// GENERATED by scripts/gate-rules.mjs from %s: do not edit. AISO only:\n'
  + '// every public read needs an honoured sign-in (#members-gate).\n';

const jobs = [
  { src: 'firestore.rules', out: 'firestore.aiso.rules', subs: [
    [/allow read;/g, 'allow read: if signedIn();'],
    [/allow read: if true;/g, 'allow read: if signedIn();'],
  ] },
  { src: 'storage.rules', out: 'storage.aiso.rules', subs: [
    [/allow read;/g, 'allow read: if isMember() || isStaff();'],
    [/allow get;/g, 'allow get: if isMember() || isStaff();'],
  ] },
];

const check = process.argv.includes('--check');
let bad = 0;
for (const { src, out, subs } of jobs) {
  let s = readFileSync(resolve(ROOT, src), 'utf8');
  for (const [re, to] of subs) s = s.replace(re, to);
  // Anything still world-readable is a new public path: decide it here.
  const left = s.match(/allow (read|get|list)(, [a-z, ]+)?: if true;|allow (read|get|list);/g);
  if (left) { console.error(`${out}: still public: ${left.join(' | ')}`); bad++; }
  s = HEAD.replace('%s', src) + s;
  if (check) {
    let cur = '';
    try { cur = readFileSync(resolve(ROOT, out), 'utf8'); } catch { /* missing */ }
    if (cur !== s) { console.error(`${out} is stale: run node scripts/gate-rules.mjs`); bad++; }
  } else {
    writeFileSync(resolve(ROOT, out), s);
  }
}
if (bad) process.exit(1);
console.log(check ? 'gate-rules: AISO rules up to date' : 'gate-rules: wrote firestore.aiso.rules, storage.aiso.rules');
